"""게임 상태 — docs/엔진_상태모델.md 1 · 2 · 3 · 6장의 코드화.

설계 문서와 어긋나지 않는 것만 담았다. 속도 최적화(9장 — 카운터 정수 enum, 되돌리기 레코드,
고정 크기 배열의 메모리 배치)는 **아직 적용하지 않았다.** 지금 필요한 것은 "맵이 실제로 돌아가는가"
이고, 최적화는 합법수 생성이 들어온 뒤 벤치마크와 함께 하는 일이다(목표_수준.md 4장).
"""

from __future__ import annotations

from dataclasses import dataclass, field
from enum import Enum
from typing import Any


class 존(Enum):
    """룰지 0장의 아홉 개 존 + 패.

    패는 0장이 나열하는 아홉 개에 **들어 있지 않다**(상태모델 1장) — 공식 존이 아니지만
    소환 · 발동의 출처라서 상태에는 반드시 있어야 한다.
    """

    메인덱 = "메인덱"      # 0-1
    상급덱 = "상급덱"      # 0-2
    아카이브 = "아카이브"  # 0-3
    공유존 = "공유존"      # 0-5, 양쪽 공유
    유닛존 = "유닛존"      # 0-4, 5칸
    이펙트존 = "이펙트존"  # 0-6, 5칸
    필드존 = "필드존"      # 0-7, 양쪽 공유 · 단일 슬롯
    스킬존 = "스킬존"      # 0-8
    공허 = "공허"          # 0-9
    패 = "패"              # 비공식


class 앞뒤(Enum):
    앞면 = "앞면"
    뒷면 = "뒷면"


class 표시(Enum):
    공격 = "공격"
    수비 = "수비"


class 단계(Enum):
    """룰지 3장의 다섯 단계. 종료 단계의 하위 a·b·c·d는 `하위단계`로 따로 둔다(상태모델 3-1)."""

    준비 = "준비"
    진행 = "진행"
    전투 = "전투"
    정비 = "정비"
    종료 = "종료"


유닛존_칸수 = 5
이펙트존_칸수 = 5


@dataclass
class 카드인스턴스:
    """상태모델 2-1. 정적 데이터는 `card_id` 로만 가리킨다(텍스트 복사 금지)."""

    card_id: str
    소유: str
    존: 존
    칸: int | None = None
    앞뒤: 앞뒤 = 앞뒤.앞면
    표시: 표시 | None = None
    카운터: dict[str, int] = field(default_factory=dict)
    턴표지: set[str] = field(default_factory=set)        # 소환됨 · 표시변경사용함 · 공격선언함 …
    효과사용횟수: dict[int, int] = field(default_factory=dict)
    무효해제시점: Any | None = None
    존입장턴: int = 0                                      # 상태모델 8-2
    상태표지: set[str] = field(default_factory=set)
    """효과가 이 카드에 걸어 둔 이름표. 덱 중립 자리이고 이름은 카드 효과가 정한다
    (호박옥의 「임시 봉인」이 지금 쓰이는 유일한 예 — 맵 3-7 · 재정 9차 로그17②)."""

    능력치증감: dict[str, int] = field(default_factory=dict)
    능력치배율: dict[str, float] = field(default_factory=dict)
    """2단계 `engine/resolve.py` 「수치」 원시 동작이 쓰는 자리 — ATK·DEF의 임시 보정치.
    기준치(카드표의 정적 ATK/DEF)와 합산하는 계산식·반올림 규칙은 아직 어떤 카드도 요구하지
    않아 정하지 않았다(완성_기준_듀얼.md 4번 — 「수치」 항목은 증감 또는 배율 중 하나를 받는다).
    필드를 벗어나거나 뒷면이 되면 `뒷면으로()`·`resolve.이동` 이 비운다."""

    def 카운터수(self, 이름: str = "봉인") -> int:
        return self.카운터.get(이름, 0)

    def 뒷면으로(self) -> None:
        """룰지 1-1 — 뒷면이 되면 처음 상태로 돌아간다. 상태모델 2-2 대로 일괄 초기화한다."""
        self.앞뒤 = 앞뒤.뒷면
        self.카운터.clear()
        self.턴표지.clear()
        self.효과사용횟수.clear()
        self.상태표지.clear()
        self.무효해제시점 = None
        self.능력치증감.clear()
        self.능력치배율.clear()


@dataclass
class 플레이어상태:
    이름: str
    hp: int = 5000
    메인덱: list[카드인스턴스] = field(default_factory=list)
    상급덱: list[카드인스턴스] = field(default_factory=list)
    아카이브: list[카드인스턴스] = field(default_factory=list)
    공허: list[카드인스턴스] = field(default_factory=list)
    패: list[카드인스턴스] = field(default_factory=list)
    유닛존: list[카드인스턴스 | None] = field(
        default_factory=lambda: [None] * 유닛존_칸수
    )
    이펙트존: list[카드인스턴스 | None] = field(
        default_factory=lambda: [None] * 이펙트존_칸수
    )
    스킬존: 카드인스턴스 | None = None
    턴표지: set[str] = field(default_factory=set)
    """이번 턴에 플레이어가 **몇 번까지만** 할 수 있는 행동의 사용 기록 — `일반소환함` 이 첫 예
    (룰지 3-2 "소환 — 횟수: 1턴에 1번"). `카드인스턴스.턴표지`(카드 단위, 예: 소환됨 ·
    표시변경사용함)와 같은 패턴을 플레이어 단위로 둔 것이다. 언제 비워지는지(턴이 바뀔 때)는
    턴 전이 엔진이 아직 없어 이 필드가 스스로 정하지 않는다 — `상태표지`와 같은 한계이고,
    지금은 시험·데모가 손으로 채우거나 비운다(합법수 생성 engine/legalmoves.py 가 읽기만 함)."""

    상태표지: set[str] = field(default_factory=set)
    """효과가 플레이어 전체에 걸어 둔 이름표 — 카드 한 장이 아니라 턴을 넘겨 지속되는 효과용.

    `카드인스턴스.상태표지`(임시 봉인 등 카드 단위)와 같은 패턴을 플레이어 단위로 둔 것(호박옥
    「침전」의 「다음 상대 턴 종료까지」 제약이 이 자리가 필요한 첫 예 — 맵 6장). 표지를 언제
    붙이고 언제 떼는지(정확한 턴 경계)는 아직 없는 턴 전이 엔진의 일이라, 지금은 상태표지의
    존재만 코드화하고 자동 만료는 다루지 않는다(상태표지 세트를 손으로 채우는 시험·데모와 같은
    수준 — 임시 봉인과 같은 한계). 이름은 카드 효과가 정하므로 술어는 표지를 읽을 뿐이다(덱 중립
    유지, docs/맵_형식.md 8장).
    """

    def 유닛들(self, 앞면만: bool = True) -> list[카드인스턴스]:
        나온것 = [칸 for 칸 in self.유닛존 if 칸 is not None]
        if 앞면만:
            나온것 = [칸 for 칸 in 나온것 if 칸.앞뒤 is 앞뒤.앞면]
        return 나온것

    def 이펙트들(self, 앞면만: bool = True) -> list[카드인스턴스]:
        나온것 = [칸 for 칸 in self.이펙트존 if 칸 is not None]
        if 앞면만:
            나온것 = [칸 for 칸 in 나온것 if 칸.앞뒤 is 앞뒤.앞면]
        return 나온것


@dataclass
class 게임상태:
    """필드 존 · 공유 존은 플레이어별이 아니라 테이블 전체에 하나다(상태모델 1-1)."""

    나: 플레이어상태
    상대: 플레이어상태
    턴번호: int = 1
    턴플레이어: str = "나"
    선공: str = "나"
    """주사위로 정해진 선공 플레이어 (룰지 2-1). 라운드당 한 번 정해지고 라운드 내내 안 바뀐다.

    룰지 3-3 "선공의 첫 턴(각 라운드의 1턴)에는 공격할 수 없다"를 판정하려고 2026-10-25(39회차,
    공격선언 조각)에 추가했다 — `턴번호 == 1 and 턴플레이어 == 선공`만으로 그 특수 턴을 가릴 수
    있다. 라운드가 바뀌면(4장 "라운드 사이") 이전 라운드 패자가 선공을 다시 정하지만, 상태모델이
    아직 라운드 경계·리셋을 다루지 않아(1장) 그 전환 자체는 이 필드의 일이 아니다 — 지금 라운드의
    선공이 누구인지만 들고 있는다."""
    단계: 단계 = 단계.진행
    하위단계: str | None = None
    필드존: 카드인스턴스 | None = None
    공유존: 카드인스턴스 | None = None
    공유존_소유마커: str | None = None
    체인: list[dict[str, Any]] = field(default_factory=list)
    """지금 쌓여 있는 체인. 각 항목 {발동자, card_id, 분류} — 분류는 '제거' 같은 효과 범주.

    처리 순서는 **룰지 3-6 b(턴 플레이어가 먼저)** 다 — rules/충돌목록.md 「판정」.
    재정 G1(상대가 먼저, LIFO)은 참고로만 남긴다. 순서를 바꿔 끼울 수 있게 함수 하나로 끊어 뒀다.

    **90회차 — 분류 `"소환"`.** `engine/turn.py` `_소환()`이 일반 소환 뒤에도 여기 한 항목을
    남긴다 — "상대가 몬스터를 소환했을 때"(다크나이트 1 · 트랩: 가시바늘 1) 반응이
    `반응형트리거_기회()`를 그대로 타게 하려면 "발동"과 같은 입구(이 리스트)가 필요했다.
    다만 소환은 룰지상 발동이 아니다(룰지 3-6: '소환 · 발동 · 로드'를 나란히 다른 항목으로
    적는다) — `체인에상대효과있음()`(engine/predicates.py)이 분류 `"소환"`을 걸러내 레시나·
    실렉스 3번("상대가 효과를 발동했을 때")이 소환만으로는 안 열리게 막는다. 새 사건 술어
    `상대몬스터소환직후()`가 분류 `"소환"`만 따로 읽는다.
    """

    마지막소환카드: 카드인스턴스 | None = None
    """방금 (일반)소환된 카드 인스턴스 그 자체 (90회차).

    `상태.체인`의 분류 `"소환"` 항목은 `반응형트리거_기회()`가 다 쓰고 나면(그 창을 열자마자
    `[]`로 비운다) 지워지지만, "그 카드를 파괴한다"(트랩: 가시바늘 1)처럼 **효과 해결
    시점**에도 "그 카드"가 누구였는지 알아야 하는 효과가 있어 따로 둔다 — `체인`과 달리
    여기서는 안 비운다(다음 소환이 그대로 덮어쓴다, `카드.턴표지`의 "소환됨"과 같이 턴이
    지나면 못 쓰게 되는 자연스러운 수명).
    """

    가용수단: set[str] = field(default_factory=set)
    """이번 턴에 **실제로 실행 가능한** 수단의 이름 집합.

    `확정수입()` 이 "내가 이번 턴에 직접 놓는다"(맵 3-3) 쪽 수입을 세려면 이 정보가 필요하고,
    그걸 스스로 알아내는 것은 합법수 생성(= 아직 없는 규칙 엔진)의 일이다. 그래서 지금은
    바깥에서 채워 넣는 입력으로 두고, 규칙 엔진이 들어오면 이 집합을 엔진이 계산해 준다.
    이것이 1층 필터와 엔진 사이에 남은 **유일한 미구현 경계**다.
    """

    def 플레이어(self, 누구: str) -> 플레이어상태:
        if 누구 == "나":
            return self.나
        if 누구 == "상대":
            return self.상대
        raise KeyError(f"없는 플레이어 {누구!r}")

    def 필드카드들(self, 누구: str) -> list[카드인스턴스]:
        """맵이 「필드」라고 쓸 때 가리키는 범위 — 그 플레이어가 지금 내놓고 있는 앞면 카드 전체.

        룰지의 「필드 존(0-7)」 하나가 아니라 유닛 존 + 이펙트 존 + (자기 것일 때) 필드 존을
        합친 것이다. 맵이 `필드.있음('호박옥 - 태고의 수해')`(필드 카드)와
        `필드.몬스터수()`(유닛 존)를 같은 접두사로 쓰기 때문에 이렇게 정의했다.
        """
        쪽 = self.플레이어(누구)
        모음 = 쪽.유닛들() + 쪽.이펙트들()
        if self.필드존 is not None and self.필드존.소유 == 누구:
            모음.append(self.필드존)
        if self.공유존 is not None and self.공유존_소유마커 == 누구:
            모음.append(self.공유존)
        return 모음
