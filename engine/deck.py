"""덱 구성 · 셔플 · 초기 패 — 완성_기준_듀얼.md 4번.

룰지 2장 그대로다.
- 2장 「덱 구성 순서」 — 스킬 카드의 태그를 가진 카드 + 공용 태그 카드로 메인 덱과 상급 덱을
  구성한다. 레벨 0~4 유닛은 메인 덱, 레벨 5~10 유닛은 상급 덱(룰지 1-1).
- 2-1 — HP 5000, 메인 덱과 상급 덱을 섞는다, 주사위로 선후공.
- 2-2 — 메인 덱과 상급 덱에서 **총 5장**을 뽑아 초기 패를 만든다.

전략 덱(0~20장)과 멀리건(2-2의 "1회에 한해 되돌리고 다시 뽑기")은 **구현하지 않았다** —
한 판을 두는 데 필요하지 않고, 어느 카드를 되돌릴지는 사람의 선택이라 자동 대전에서 정할
근거가 없다. `docs/듀얼_점검.md` 미구현 목록에 적어 뒀다.
"""

from __future__ import annotations

import random
from dataclasses import dataclass

from .state import 게임상태, 존, 카드인스턴스, 플레이어상태
from .static import 기본카드표, 카드표

공용태그 = "공용"


@dataclass(frozen=True)
class 덱정의:
    """한 플레이어가 들고 오는 것. `테마`가 스킬 카드의 태그 역할을 한다."""

    테마: str
    메인덱: tuple[str, ...]
    상급덱: tuple[str, ...]
    스킬: str | None


def 덱_만들기(테마: str, 표: 카드표 | None = None, 공용포함: bool = True) -> 덱정의:
    """카드 풀에서 그 테마의 덱을 통째로 꺼낸다(룰지 2장 「덱 구성 순서」).

    매수는 각 카드 1장씩이다 — 룰지가 같은 카드의 매수 상한을 말하지 않아(2장 전체에 그런
    조항이 없다) 추측으로 늘리지 않았다. 늘릴 근거가 생기면 여기만 고치면 된다.
    """
    표 = 표 or 기본카드표()
    메인: list[str] = []
    상급: list[str] = []
    스킬: str | None = None
    테마들 = {테마} | ({공용태그} if 공용포함 else set())

    for 이름 in 표.이름들():
        정의 = 표[이름]
        if 정의.theme not in 테마들:
            continue
        if 정의.type == "스킬":
            # 스킬 카드는 덱에 넣지 않고 스킬 존에 놓인다(룰지 1-4 · 2-1).
            if 정의.theme == 테마 and 스킬 is None:
                스킬 = 이름
            continue
        if 정의.몬스터인가 and (정의.level or 0) >= 5:
            상급.append(이름)
        else:
            메인.append(이름)

    return 덱정의(테마=테마, 메인덱=tuple(메인), 상급덱=tuple(상급), 스킬=스킬)


def _인스턴스들(이름들: tuple[str, ...], 소유: str, 존이름: 존) -> list[카드인스턴스]:
    return [카드인스턴스(card_id=이름, 소유=소유, 존=존이름) for 이름 in 이름들]


def 플레이어_세팅(
    이름: str, 덱: 덱정의, 난수: random.Random, 표: 카드표 | None = None
) -> 플레이어상태:
    """HP 5000 · 두 덱 셔플 · 스킬 카드 배치 (룰지 2-1). 초기 패는 아직 안 뽑는다."""
    표 = 표 or 기본카드표()
    쪽 = 플레이어상태(이름=이름, hp=5000)
    쪽.메인덱 = _인스턴스들(덱.메인덱, 이름, 존.메인덱)
    쪽.상급덱 = _인스턴스들(덱.상급덱, 이름, 존.상급덱)
    난수.shuffle(쪽.메인덱)
    난수.shuffle(쪽.상급덱)
    if 덱.스킬 is not None:
        쪽.스킬존 = 카드인스턴스(card_id=덱.스킬, 소유=이름, 존=존.스킬존)
    return 쪽


def 뽑기(쪽: 플레이어상태, 어느덱: str = "메인덱") -> 카드인스턴스 | None:
    """덱 맨 위 한 장을 패로. 뽑을 수 없으면 None (룰지 4장 b — 패배 조건이 된다)."""
    더미 = 쪽.메인덱 if 어느덱 == "메인덱" else 쪽.상급덱
    if not 더미:
        return None
    카드 = 더미.pop(0)
    카드.존 = 존.패
    카드.칸 = None
    쪽.패.append(카드)
    return 카드


def 초기패(쪽: 플레이어상태, 난수: random.Random, 장수: int = 5) -> None:
    """룰지 2-2 — 메인 덱과 상급 덱에서 **총 5장**.

    어느 덱에서 몇 장을 뽑을지는 플레이어가 정하는 것인데(2-2가 매수 배분을 플레이어에게
    맡긴다), 자동 대전에는 그 선택을 할 사람이 없다. 그래서 **남아 있는 덱 중에서 무작위로**
    고른다 — 추측한 전략이 아니라 선택 자체를 난수에 넘긴 것이고, 시드가 같으면 재현된다.
    """
    for _ in range(장수):
        후보 = [이름 for 이름 in ("메인덱", "상급덱") if getattr(쪽, 이름)]
        if not 후보:
            return
        뽑기(쪽, 난수.choice(후보))


def 대전_준비(
    나_테마: str,
    상대_테마: str,
    시드: int = 0,
    표: 카드표 | None = None,
) -> tuple[게임상태, random.Random]:
    """룰지 2장 전체 — 두 덱을 만들고 섞고 초기 패 5장씩, 주사위로 선공 결정.

    주사위(2-1 "더 높은 사람이 결정권")는 **같은 눈이 나오면 다시 굴린다**. 결정권을 가진
    쪽이 선공을 고르는 것도 사람의 선택이므로, 여기서는 "이긴 쪽이 선공"으로 둔다 —
    `docs/듀얼_점검.md` 미구현 목록 참조.
    """
    표 = 표 or 기본카드표()
    난수 = random.Random(시드)

    나덱 = 덱_만들기(나_테마, 표)
    상대덱 = 덱_만들기(상대_테마, 표)
    나 = 플레이어_세팅("나", 나덱, 난수, 표)
    상대 = 플레이어_세팅("상대", 상대덱, 난수, 표)

    while True:
        내눈, 상대눈 = 난수.randint(1, 6), 난수.randint(1, 6)
        if 내눈 != 상대눈:
            break
    선공 = "나" if 내눈 > 상대눈 else "상대"

    초기패(나, 난수)
    초기패(상대, 난수)

    상태 = 게임상태(나=나, 상대=상대, 턴번호=1, 턴플레이어=선공, 선공=선공)
    return 상태, 난수
