"""효과 해결 — 2단계 완성 기준 항목1(상태 전이).

`docs/완성_기준_듀얼.md` 4번이 못 박은 **다섯 원시 동작**(이동 · 카운터 · 수치 · 표시변경 · 금지)
만 여기 있다. 여섯 번째를 만들지 않는다. 각 함수는 `게임상태`를 그 자리에서 바꾸는 부작용
함수이고 값을 돌려주는 것은 호출자 편의(다음 동작에 바로 넘기기)일 뿐이다.

**경계 — 이 파일은 "원시 동작을 적용하면 상태가 어떻게 바뀌는가"만 안다.** 어느 카드가 어느
타이밍에 이 함수들을 어떤 인수로 부르는지(효과 데이터 해석)는 항목2(`cards/효과/<덱>.yaml` +
그걸 읽는 해석기)의 일이고, 그 해석기는 아직 없다. 1단계의 경계(「발동할 수 있는가」만, 「발동
하면 무엇이 일어나는가」는 2단계)와 짝을 이루는 2단계 내부의 다음 경계 — "무엇을 적용할지 정하는
것"과 "적용 그 자체"를 나눴다.

승패 판정(LP 0 등, 항목5) · 체인/타이밍 순서(항목3) · 효과 소유자 판정은 이 파일의 일이 아니다.
여기 함수들은 상태를 바꿀 뿐, 그 결과가 무엇을 뜻하는지는 해석하지 않는다.
"""

from __future__ import annotations

from .state import (
    게임상태,
    카드인스턴스,
    플레이어상태,
    존,
    표시,
)
from .state import 앞뒤 as _앞뒤


class 해결오류(Exception):
    """원시 동작을 적용할 수 없는 상태 — 잘못된 존 · 소유 · 칸 지정, 빈 칸 없음 등."""


# ---------------------------------------------------------------- 공통 헬퍼

_목록존 = (존.메인덱, 존.상급덱, 존.아카이브, 존.공허, 존.패)
_슬롯존 = (존.유닛존, 존.이펙트존)        # 칸 번호가 있는 리스트
_단일존 = (존.필드존, 존.공유존, 존.스킬존)  # 칸이 아니라 속성 하나
_필드존들 = (존.유닛존, 존.이펙트존, 존.필드존, 존.공유존)
"""상태모델 6장 "카드가 필드를 벗어남" 판정에 쓰는 범위. 스킬 존은 필드가 아니다(룰지 0장)."""


def _리스트존(쪽: 플레이어상태, 존이름: 존) -> list[카드인스턴스]:
    매핑 = {
        존.메인덱: 쪽.메인덱,
        존.상급덱: 쪽.상급덱,
        존.아카이브: 쪽.아카이브,
        존.공허: 쪽.공허,
        존.패: 쪽.패,
    }
    목록 = 매핑.get(존이름)
    if 목록 is None:
        raise 해결오류(f"목록형 존이 아니다 — {존이름}")
    return 목록


def _빼기(상태: 게임상태, 카드: 카드인스턴스) -> None:
    """카드를 지금 있는 자리에서 뗀다. 자리가 이미 비어 있으면(=손으로 미리 뗀 경우) 조용히 넘어간다."""
    존이름 = 카드.존
    if 존이름 is 존.필드존:
        if 상태.필드존 is 카드:
            상태.필드존 = None
        return
    if 존이름 is 존.공유존:
        if 상태.공유존 is 카드:
            상태.공유존 = None
            상태.공유존_소유마커 = None
        return

    쪽 = 상태.플레이어(카드.소유)
    if 존이름 is 존.스킬존:
        if 쪽.스킬존 is 카드:
            쪽.스킬존 = None
        return
    if 존이름 in _슬롯존:
        슬롯 = 쪽.유닛존 if 존이름 is 존.유닛존 else 쪽.이펙트존
        for i, 자리카드 in enumerate(슬롯):
            if 자리카드 is 카드:
                슬롯[i] = None
                return
        return
    목록 = _리스트존(쪽, 존이름)
    if 카드 in 목록:
        목록.remove(카드)


def _넣기(
    상태: 게임상태,
    카드: 카드인스턴스,
    로: 존,
    소유: str,
    칸: int | None,
    맨아래: bool,
) -> None:
    카드.소유 = 소유
    카드.존 = 로

    if 로 is 존.필드존:
        if 상태.필드존 is not None:
            raise 해결오류("필드 존이 이미 차 있다 — 단일 슬롯(룰지 0-7)")
        상태.필드존 = 카드
        카드.칸 = None
        return
    if 로 is 존.공유존:
        if 상태.공유존 is not None:
            raise 해결오류("공유 존이 이미 차 있다 — 단일 슬롯(룰지 0-5)")
        상태.공유존 = 카드
        상태.공유존_소유마커 = 소유
        카드.칸 = None
        return

    쪽 = 상태.플레이어(소유)
    if 로 is 존.스킬존:
        if 쪽.스킬존 is not None:
            raise 해결오류(f"{소유}의 스킬 존이 이미 차 있다 — 단일 슬롯(룰지 0-8)")
        쪽.스킬존 = 카드
        카드.칸 = None
        return
    if 로 in _슬롯존:
        슬롯 = 쪽.유닛존 if 로 is 존.유닛존 else 쪽.이펙트존
        if 칸 is not None:
            if 슬롯[칸] is not None:
                raise 해결오류(f"{로.value} {칸}번 칸이 이미 차 있다")
            슬롯[칸] = 카드
            카드.칸 = 칸
            return
        for i, 자리 in enumerate(슬롯):
            if 자리 is None:
                슬롯[i] = 카드
                카드.칸 = i
                return
        raise 해결오류(f"{소유}의 {로.value} 에 빈 칸이 없다(칸수 {len(슬롯)})")

    목록 = _리스트존(쪽, 로)
    카드.칸 = None
    if 로 in (존.메인덱, 존.상급덱):
        # 덱만 "맨 위/맨 아래" 가 뜻이 있다 — 위치 0 = 맨 위, 기본은 맨 위에 넣는다.
        목록.insert(len(목록) if 맨아래 else 0, 카드)
    else:
        # 패 · 아카이브 · 공허는 순서에 규칙상 의미가 없다 — 들어온 순서대로 쌓는다.
        목록.append(카드)


def _단일카드_이동(
    상태: 게임상태,
    카드: 카드인스턴스,
    로: 존,
    *,
    소유: str | None,
    칸: int | None,
    맨아래: bool,
    공수: 표시 | None,
    앞뒤: _앞뒤 | None,
) -> 카드인스턴스:
    이전존 = 카드.존
    목적지_소유 = 소유 if 소유 is not None else 카드.소유

    _빼기(상태, 카드)
    _넣기(상태, 카드, 로, 목적지_소유, 칸, 맨아래)

    카드.존입장턴 = 상태.턴번호  # 상태모델 8-2

    # 상태모델 6장 — 카드가 "필드"(유닛·이펙트·필드·공유 존)를 완전히 벗어나면 카운터가 리셋된다.
    if 이전존 in _필드존들 and 로 not in _필드존들:
        카드.카운터.clear()
        # 「필드이탈됨」 턴표지(86회차, 「알려진 틈」 1번 — 꿈의 파열) — 재정 호박옥6(황금봉랍
        # 2번 "상대 효과로 덱·제외 존으로 간 경우: 발동한다. 「필드를 벗어났을 때」이므로
        # 가는 곳을 가리지 않는다")을 그대로 따라, 가는 곳(아카이브든 패든 덱이든 공허든)을
        # 안 가리고 "필드 네 존 중 하나를 떠났다"는 사건 자체에만 켠다. 아래 "아카이브로보내짐"
        # (84회차, [유언] 전용 — 목적지가 아카이브인 경우만)과는 범위가 다른 별개 표지다 — 한
        # 카드가 아카이브로 가면 둘 다 켜질 수 있다.
        카드.턴표지.add("필드이탈됨")

    # [유언] 창 열기(84회차, 「알려진 틈」 3번 — 강제 트리거) — 룰지 5장 키워드표 "[유언]
    # (조건) 자신이 **아카이브로 보내졌을 때** 사용 가능"은 원인(전투 파괴·효과·코스트·계승)도
    # 원래 있던 존(필드·패·덱)도 가리지 않는다. 3-2 "계승은 파괴가 아니다 — … [유언]은
    # 일어난다"가 그 근거를 더 분명히 한다(파괴가 아닌 계승에도 열리므로, 필드를 벗어나는
    # 경로로 좁힐 근거가 없다). `engine/predicates.py` `유언직후()`가 이미 기대하는
    # `카드인스턴스.턴표지` 의 `"아카이브로보내짐"` 문자열을 여기서 켠다 — 지금까지는
    # `tests/test_filter.py` 가 손으로 켜 둔 값이었고, 실제 듀얼 엔진에는 이 전환점이 없었다.
    # 같은 카드 인스턴스가 전에 다른 자리에서 쓴 `효과사용횟수`는 이 새 아카이브行(行)과
    # 무관한 과거 기록이라 같이 비운다 — "쓴 뒤에도 카드가 남는" 강제 [유언](84회차, 던전마스터
    # 8장)이 특수소환으로 돌아왔다가 다시 죽는 경우에도 또 발동해야 하는데, 안 비우면 예전
    # 번호가 그대로 남아 두 번째 발동을 막는다(`engine/predicates.py` `유언직후()` 머리글의
    # "카드가 아카이브에 남는 [유언] 효과가 생기면 그때 가서 같이 걸어야 한다"가 가리킨 바로
    # 그 경우).
    if 로 is 존.아카이브 and 이전존 is not 존.아카이브:
        카드.턴표지.add("아카이브로보내짐")
        카드.효과사용횟수.clear()

    if 앞뒤 is _앞뒤.뒷면:
        카드.뒷면으로()  # 룰지 1-1 — 앞뒤·카운터·턴표지·효과사용횟수·상태표지·보정치 전부 초기화
    elif 앞뒤 is _앞뒤.앞면:
        카드.앞뒤 = _앞뒤.앞면

    if 로 is 존.유닛존:
        카드.표시 = 공수 if 공수 is not None else (카드.표시 or 표시.공격)
        # 표시를 명시하지 않은 소환은 공격 표시가 기본이다(룰지 3-2) — 이미 수비였으면 유지.
    elif 공수 is not None:
        카드.표시 = 공수
    elif 로 not in _단일존:
        카드.표시 = None  # 유닛 존을 벗어나면(필드·공유·스킬 존 제외) 표시 개념이 사라진다

    return 카드


# ---------------------------------------------------------------- 1. 이동

def 이동(
    상태: 게임상태,
    로: 존,
    *,
    카드: 카드인스턴스 | None = None,
    에서: 존 | None = None,
    에서소유: str | None = None,
    수: int = 1,
    소유: str | None = None,
    칸: int | None = None,
    맨아래: bool = False,
    공수: 표시 | None = None,
    앞뒤: _앞뒤 | None = _앞뒤.앞면,
) -> list[카드인스턴스]:
    """카드를 다른 존으로 옮긴다.

    파괴 · 묘지로 · 되돌리기 · 제외 · 드로우 · 소환 · 특수소환 · 세트 · 덱 맨 — 완성_기준_듀얼.md
    표의 9개 서술어를 전부 이 함수 하나로 흡수한다. 구체 카드 꼴(파괴 등)은 `카드=`를,
    "덱 맨 위에서 N장"처럼 특정 카드를 안 고르는 꼴(드로우)은 `에서=`·`수=`를 쓴다.

    - `카드`를 주면 그 한 장만 옮긴다. 소유는 생략하면 카드의 원래 소유를 유지한다(컨트롤이
      넘어가는 효과는 `소유=`로 명시).
    - `카드`가 없으면 `(에서소유 또는 소유, 에서)` 존의 **맨 위**(목록 인덱스 0)에서 `수`장을
      순서대로 옮긴다 — 드로우가 전형이다. 목록형 존(메인덱 · 상급덱 · 아카이브 · 공허 · 패)만
      이 모드를 받는다.
    - `앞뒤=앞뒤.뒷면`이면 세트. 기본값은 앞면이고, `앞뒤=None`을 주면 카드의 기존 앞뒤를
      유지한 채로만 옮긴다(이미 뒷면인 카드를 묘지로 보내는 등).
    - `맨아래=True`는 "덱 맨 아래로" 변형(상태모델 설계상 맨 위=인덱스 0을 기본으로 삼았다).
    """
    if 카드 is not None:
        return [_단일카드_이동(상태, 카드, 로, 소유=소유, 칸=칸, 맨아래=맨아래, 공수=공수, 앞뒤=앞뒤)]

    if 에서 is None:
        raise 해결오류("카드를 지정하지 않았으면 에서(출발 존)가 있어야 한다")
    출발소유 = 에서소유 if 에서소유 is not None else 소유
    if 출발소유 is None:
        raise 해결오류("카드를 지정하지 않았으면 에서소유(또는 소유)가 있어야 한다")
    if 에서 not in _목록존:
        raise 해결오류(f"카드 없이 옮길 수 있는 것은 목록형 존뿐이다 — {에서}")

    목록 = _리스트존(상태.플레이어(출발소유), 에서)
    뽑힌것: list[카드인스턴스] = []
    for _ in range(수):
        if not 목록:
            break
        뽑힌것.append(목록.pop(0))
    결과: list[카드인스턴스] = []
    for 하나 in 뽑힌것:
        결과.append(
            _단일카드_이동(상태, 하나, 로, 소유=소유, 칸=칸, 맨아래=맨아래, 공수=공수, 앞뒤=앞뒤)
        )
    return 결과


# ---------------------------------------------------------------- 2. 카운터

def 카운터(상태: 게임상태, 카드: 카드인스턴스, 증감: int, 이름: str = "봉인") -> int:
    """카드 위 카운터를 놓거나(양수) 뗀다(음수). 봉인 카운터 놓기·떼기·코스트 소모를 흡수한다.

    0 밑으로는 못 내려간다 — 뗄 수 있는 것은 있는 만큼뿐이다. 결과 값을 돌려준다.
    """
    새값 = 카드.카운터수(이름) + 증감
    if 새값 < 0:
        raise 해결오류(
            f"{카드.card_id} 의 {이름} 카운터를 {-증감}개 떼려 했지만 {카드.카운터수(이름)}개뿐이다"
        )
    if 새값 == 0:
        카드.카운터.pop(이름, None)
    else:
        카드.카운터[이름] = 새값
    return 새값


# ---------------------------------------------------------------- 3. 수치

_수치종류 = ("LP", "ATK", "DEF")


def 수치(
    상태: 게임상태,
    대상: 카드인스턴스 | 플레이어상태 | str,
    무엇: str,
    *,
    증감: int | None = None,
    배율: float | None = None,
) -> int | float:
    """ATK · DEF · LP 를 바꾼다. 대미지 · 회복 · 올린 · 내린 · 반으로를 흡수한다.

    `증감`과 `배율`은 **배타적**이다(카드 하나가 둘 다 요구하면 두 번 부른다). ATK/DEF는
    `카드인스턴스.능력치증감`·`능력치배율`에 누적하기만 한다 — 카드표의 기준치와 합산하는
    계산식·반올림 규칙은 아직 어떤 카드도 요구하지 않아 여기서 정하지 않는다(state.py 주석
    참조, 추측 금지). LP 는 `플레이어상태.hp`를 직접 바꾼다. 0 이하가 됐을 때의 판정(패배)은
    이 함수의 일이 아니다 — 항목5(승패 판정)가 `hp`를 읽고 판단한다.
    """
    if 무엇 not in _수치종류:
        raise 해결오류(f"수치 종류는 {_수치종류} 뿐이다 — {무엇!r}")
    if (증감 is None) == (배율 is None):
        raise 해결오류("수치는 증감 또는 배율 중 정확히 하나를 받는다")

    if 무엇 == "LP":
        쪽 = 상태.플레이어(대상) if isinstance(대상, str) else 대상
        if not isinstance(쪽, 플레이어상태):
            raise 해결오류(f"LP 대상은 플레이어라야 한다 — {대상!r}")
        쪽.hp = 쪽.hp + 증감 if 증감 is not None else round(쪽.hp * 배율)
        return 쪽.hp

    if not isinstance(대상, 카드인스턴스):
        raise 해결오류(f"{무엇} 수정 대상은 카드라야 한다 — {대상!r}")
    if 증감 is not None:
        대상.능력치증감[무엇] = 대상.능력치증감.get(무엇, 0) + 증감
        return 대상.능력치증감[무엇]
    대상.능력치배율[무엇] = 대상.능력치배율.get(무엇, 1.0) * 배율
    return 대상.능력치배율[무엇]


# ---------------------------------------------------------------- 4. 표시변경

def 표시변경(
    상태: 게임상태,
    카드: 카드인스턴스,
    *,
    앞뒤: _앞뒤 | None = None,
    공수: 표시 | None = None,
) -> None:
    """카드의 앞뒤 또는 공격/수비 표시를 바꾼다. 둘 중 하나만 줘도 된다(동시에 줄 수도 있다).

    뒷면으로 바뀌는 순간은 `카드인스턴스.뒷면으로()`를 그대로 써서 룰지 1-1 초기화를 받는다
    (`이동`의 세트와 같은 경로). 필드를 벗어나는 이동이 아니므로 `이동`과 분리된 함수다.
    """
    if 앞뒤 is None and 공수 is None:
        raise 해결오류("표시변경은 앞뒤 또는 공수 중 적어도 하나를 받아야 한다")
    if 앞뒤 is _앞뒤.뒷면 and 카드.앞뒤 is not _앞뒤.뒷면:
        카드.뒷면으로()
        if 공수 is not None:
            카드.표시 = 공수
        return
    if 앞뒤 is not None:
        카드.앞뒤 = 앞뒤
    if 공수 is not None:
        카드.표시 = 공수


# ---------------------------------------------------------------- 5. 금지

def 금지(
    상태: 게임상태,
    대상: 카드인스턴스 | 플레이어상태,
    무엇: str,
    기간: str,
) -> str:
    """발동 · 공격 · 효과 적용을 막는 이름표를 건다. 무효 · 발동할 수 없다 · 공격할 수 없다 ·
    [지속] 제약을 흡수한다.

    표지는 `"금지:{무엇}:{기간}"` 꼴로 대상의 `상태표지`에 쌓인다 — `카드인스턴스.상태표지` ·
    `플레이어상태.상태표지`는 이미 1단계 설계가 "이름은 효과가 정한다"로 열어 둔 자리다
    (`engine/state.py` 주석, 호박옥 「임시 봉인」과 같은 패턴). **표지를 언제 떼는지는 이
    함수의 일이 아니다** — `docs/엔진_상태모델.md` 7장이 턴 전이 엔진(항목3)의 일로 넘겨 둔
    경계를 그대로 따른다. 이미 걸려 있으면 다시 걸어도 변화 없다(집합이라 중복이 없다).
    """
    if not isinstance(대상, (카드인스턴스, 플레이어상태)):
        raise 해결오류(f"금지 대상은 카드 또는 플레이어라야 한다 — {대상!r}")
    표지 = f"금지:{무엇}:{기간}"
    대상.상태표지.add(표지)
    return 표지
