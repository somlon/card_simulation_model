def 반응형트리거_기회(
    상태: 게임상태,
    표: 카드표,
    상수표: dict[str, 덱상수],
    역할: dict[str, object],
    효과적용: Callable[..., bool],
    기록: 기보,
) -> None:
    """임의 [트리거] 반응 창 (88회차, 「알려진 틈」 1번의 마지막 큰 조각).

    `scripts/듀얼.py`·`engine/room.py`의 턴 루프는 **턴 플레이어만** 묻는다
    (`합법수_생성(상태, 표, 누구, ...)`가 `누구 = 상태.턴플레이어`로만 불린다) — 이 함수가
    생기기 전까지 상대는 자기 턴이 아닐 때 "상대가 효과를 발동했을 때" 꼴의 [트리거]를
    쓸 자리가 아예 없었다(53회차가 1층 발동 조건까지는 열어 뒀지만 2단계 턴 루프에 그
    자리를 실제로 묻는 호출이 없었다는 뜻, `engine/legalmoves.py` `트리거반응_후보들()`
    머리글 참조).

    `수_적용()`·`강제트리거_처리()`가 "발동" 하나마다 `상태.체인`을 1건으로 갈아 치워 둔다
    (그 발동이 효과 미구현이라 아무 상태도 못 바꿨어도 "발동을 선언했다"는 사실은 남는다).
    이 함수는 그걸 읽어 **발동자의 상대**에게 `트리거반응_후보들()`을 묻고, 그 역할의
    `수_고르기()`를 그대로 재사용해 사람 · 무작위 · 필터 세 역할이 똑같이 응답하게 한다
    (새 인터페이스를 안 만들고 메인 턴 루프가 이미 쓰는 자리를 그대로 썼을 뿐이다) —
    `None`(빈 줄 · 맵이 전부 떨어뜨림)이면 "안 함"이고 그걸로 창이 닫힌다.

    반응 자체도 "발동"이라 `수_적용()`이 `상태.체인`을 다시 채운다 — 반응자가 쓴 카드에
    또 반응할 상대쪽(원래 발동자)이 있는지까지 보려고 루프를 돈다(상한 10회,
    `강제트리거_처리()`의 20회 상한과 같은 "조용히 안 삼킨다" 철학 — 실제로는
    `효과사용횟수` 제한이나 플레이어의 "안 함" 선택으로 금방 끝난다).
    """
    for _ in range(10):
        if not 상태.체인:
            return
        최근발동자 = 상태.체인[-1].get("발동자")
        반응자 = "상대" if 최근발동자 == "나" else "나"
        상수 = 상수표[반응자]
        후보 = sorted(트리거반응_후보들(상태, 표, 반응자, 상수))
        상태.체인 = []  # 창을 한 번 열면 비운다 — 같은 발동에 두 번 반응 기회를 주지 않는다
        if not 후보:
            return
        나역 = 역할[반응자]
        고른수 = 나역.수_고르기(상태, 후보, 반응자)
        if getattr(나역, "기권했나", False):
            return
        if 고른수 is None:
            return
        수_적용(
            상태, 고른수, 누구=반응자, 표=표, 상수=상수,
            고르기=나역.고르기, 기록=기록, 효과적용=효과적용,
        )
        강제트리거_처리(상태, 표, 상수표, 효과적용, 나역.고르기, 기록)
    raise 적용오류("반응형 트리거 처리가 10회를 넘겨 끝나지 않았다 — 데이터 오류로 보인다")


def 턴표지_정리(쪽: 플레이어상태) -> None:
    """룰지 3-5 「정리」 — 턴이 끝나면 그 턴만의 표지를 지운다.

    효과사용횟수도 함께 비운다(룰지 1장 전역 규칙 — 모든 효과는 1턴에 1번).
    """
    쪽.턴표지.clear()
    for 카드 in 쪽.유닛들(앞면만=False) + 쪽.이펙트들(앞면만=False):
        for 표지 in ("소환됨", "표시변경사용함", "공격선언함", "로드한턴"):
            카드.턴표지.discard(표지)
        카드.효과사용횟수.clear()


def 준비단계(상태: 게임상태, 누구: str, 고르기: 선택자, 기록: 기보) -> 종료 | None:
    """룰지 3-1 — 메인 덱 또는 상급 덱에서 한 장. 첫 턴에는 실시하지 않는다.

    뽑을 수 없으면 룰지 4장 b 로 그 자리에서 패배다.
    """
    상태.단계 = 단계.준비
    쪽 = 상태.플레이어(누구)
    if 상태.턴번호 == 1 and 누구 == 상태.선공:
        기록.적기("  " + 누구 + ": 선공 첫 턴 — 드로우 없음 (룰지 3-1)")
        return None
    if not _뽑을_수_있나(쪽):
        반대 = "상대" if 누구 == "나" else "나"
