                # 88회차 — 강제 발동도 "발동"이다(위 `수_적용`의 같은 자리 참조). 한 묶음 안에
                # 여러 강제 효과가 연쇄로 발동하면 마지막 것만 남는다 — 드물게 놓치는 반응이
