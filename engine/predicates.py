    def _수입정의들(self):
        for 이름 in self.카드표.이름들():
            정의 = self.카드표[이름]
            if 정의.수입:
                yield 정의

    def _유닛찾기(self, 유닛: str | 카드인스턴스 | None) -> 카드인스턴스 | None:
        if 유닛 is None or isinstance(유닛, 카드인스턴스):
            return 유닛
        for 하나 in self.상태.필드카드들(self.나는):
            if 하나.card_id == 유닛:
                return 하나
        return None

    def _아카이브찾기(self, 카드: str) -> 카드인스턴스 | None:
        """`_유닛찾기()`의 아카이브 자매 함수 (78회차, [유언] 키워드가 처음 필요로 했다) —
        필드가 아니라 자신 아카이브에서 인스턴스를 찾는다."""
        for 하나 in self.상태.플레이어(self.나는).아카이브:
            if 하나.card_id == 카드:
                return 하나
        return None

    def _전역찾기(self, 카드: str) -> 카드인스턴스 | None:
        """`필드이탈직후()`(86회차)가 쓰는 자리 — 목적지를 안 가리므로 자신이 가진 존 전부
        (유닛·이펙트·패·아카이브·메인덱·상급덱·공허·스킬존)를 본다. `_유닛찾기`·`_아카이브찾기`
        보다 넓은 마지막 수단이라 다른 함수가 좁은 범위로 충분하면 그쪽을 쓴다."""
        쪽 = self.상태.플레이어(self.나는)
        모두 = (
            쪽.유닛들(앞면만=False) + 쪽.이펙트들(앞면만=False) + 쪽.패 + 쪽.아카이브
            + 쪽.메인덱 + 쪽.상급덱 + 쪽.공허
            + ([쪽.스킬존] if 쪽.스킬존 else [])
        )
        return next((하나 for 하나 in 모두 if 하나.card_id == 카드), None)

