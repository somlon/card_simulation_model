"""보드 스냅샷 — 상태를 **한 자리에서 보이는 대로** 사전으로 만든다.

화면(웹·CLI)이 공통으로 쓴다. 룰지 0장의 아홉 존을 그대로 담고, 그 자리에서 보면 안 되는
것은 담지 않는다 — 상대의 뒷면 카드(룰지 1-1)와 남의 패다. **가리는 일을 화면에 맡기지
않는다**: 보내지 않은 것은 브라우저 개발자 도구로도 안 보인다.

룰지 0장 배치(「자신 쪽 필드의 배치 예시」) — 화면은 이 꼴로 그린다.

    [스킬존] [유닛1][유닛2][유닛3][유닛4][유닛5] [아카이브][공허]
      (빈)   [이펙1][이펙2][이펙3][이펙4][이펙5] [메인덱][상급덱]

필드 존(0-7)과 공유 존(0-5)은 **두 플레이어 사이**에 한 칸씩 놓인다.
"""

from __future__ import annotations

import re

from .state import 게임상태, 앞뒤, 카드인스턴스
from .static import 카드표

색표 = {
    "적색": "적", "녹색": "녹", "황색": "황", "청색": "청",
    "자색": "자", "백색": "백", "흑색": "흑",
}


def 카드_딕(하나: 카드인스턴스 | None, 표: 카드표, 가릴까: bool = False) -> dict | None:
    """카드 한 장. `가릴까` 면 뒷면 카드의 정체를 **아예 보내지 않는다**."""
    if 하나 is None:
        return None
    뒷면 = 하나.앞뒤 is 앞뒤.뒷면
    if 뒷면 and 가릴까:
        return {"뒷면": True, "이름": None, "텍스트": "", "색": None,
                "공": None, "수": None, "레벨": None, "카운터": 0, "표시": None,
                "종류": None, "표지": []}
    정의 = 표.찾기(하나.card_id)
    몬 = bool(정의 and 정의.몬스터인가)
    return {
        "뒷면": 뒷면,
        "이름": 하나.card_id,
        "텍스트": (정의.text if 정의 else "") or "",
        "색": 색표.get((정의.color if 정의 else "") or "", None),
        "종류": (정의.type if 정의 else None),
        "공": 정의.atk if 몬 else None,
        "수": 정의.df if 몬 else None,
        "레벨": 정의.level if 몬 else None,
        "카운터": 하나.카운터수(),
        "표시": 하나.표시.value if 하나.표시 else None,
        "표지": sorted(하나.상태표지),
    }


def 보드_딕(상태: 게임상태, 표: 카드표, 보는이: str | None = "나") -> dict:
    """`보는이` 자리에서 보이는 판. `None` 이면 관전(양쪽 패와 뒷면을 전부 가린다)."""
    쪽들 = {}
    for 이름 in ("나", "상대"):
        쪽 = 상태.플레이어(이름)
        가릴까 = 이름 != 보는이        # 내 뒷면은 나만 본다 (룰지 1-1)
        쪽들[이름] = {
            "hp": 쪽.hp,
            "패수": len(쪽.패),
            "메인덱": len(쪽.메인덱),
            "상급덱": len(쪽.상급덱),
            "아카이브": [카드_딕(하나, 표) for 하나 in 쪽.아카이브],   # 0-3 앞면·공개
            "공허": [카드_딕(하나, 표) for 하나 in 쪽.공허],           # 0-9 앞면·공개
            "스킬": 카드_딕(쪽.스킬존, 표),                            # 0-8 처음부터 공개
            "유닛": [카드_딕(하나, 표, 가릴까) for 하나 in 쪽.유닛존],   # 0-4 5칸
            "이펙트": [카드_딕(하나, 표, 가릴까) for 하나 in 쪽.이펙트존],  # 0-6 5칸
            "패": ([카드_딕(하나, 표) for 하나 in 쪽.패] if 이름 == 보는이 else []),
            "표지": sorted(쪽.상태표지),
        }
    return {
        "턴": 상태.턴번호,
        "턴플레이어": 상태.턴플레이어,
        "단계": 상태.단계.value,
        "선공": 상태.선공,
        "보는이": 보는이,
        "필드존": 카드_딕(상태.필드존, 표),            # 0-7 양쪽 공유 1칸
        "공유존": 카드_딕(상태.공유존, 표),            # 0-5 양쪽 공유 1칸
        "공유존주인": 상태.공유존_소유마커,            # 마커로 주인 표시
        "체인": list(상태.체인),
        "쪽": 쪽들,
    }


# ---------------------------------------------------------------------------
# 효과 문면 — "무슨 효과를 쓴 건지" 화면에 붙여 주는 조각
#
# 사용자 요청(2026-10-28): 기보와 수 선택지가 "카드이름 N번 발동" 뿐이라 카드 텍스트를
# 전부 적어 두지 않으면 못 읽는다. 카드 정의의 `text` 를 번호별로 쪼개 그 자리에 붙인다.
# **규칙은 여기 없다** — 보여 주기만 하고, 무엇이 실제로 일어나는지는 `engine/effects.py`
# 가 정한다(구현이 비어 있으면 기보에 「효과 미구현」이 따로 붙는다).
# ---------------------------------------------------------------------------

_번호꼴 = re.compile(r"(?:(?<=\s)|^)(\d{1,2})\.\s")


def 효과조각들(텍스트: str) -> dict[int, str]:
    """카드 텍스트를 효과 번호별로 쪼갠다 — `"1. [소환] … 2. [유언] …"` → `{1: …, 2: …}`.

    번호가 **1부터 하나씩 늘어나는 것만** 머리로 인정한다. 문장 안의 "1000 대미지" 같은
    숫자나 「럭키 다이스」의 "- 1: …" 같은 가짓수 목록을 효과 머리로 잘못 읽지 않기 위해서다.
    번호 꼴이 아예 없으면 전체를 1번 하나로 본다(실제로 그런 카드가 있다).
    """
    글 = (텍스트 or "").strip()
    if not 글:
        return {}
    머리들 = []
    다음 = 1
    for 맞음 in _번호꼴.finditer(글):
        if int(맞음.group(1)) != 다음:
            continue
        머리들.append((다음, 맞음.start(), 맞음.end()))
        다음 += 1
    if not 머리들:
        return {1: 글}
    조각 = {}
    for 자리, (번호, 시작, 끝) in enumerate(머리들):
        마침 = 머리들[자리 + 1][1] if 자리 + 1 < len(머리들) else len(글)
        조각[번호] = 글[끝:마침].strip()
    return 조각


def 효과문(표: 카드표, 카드이름: str, 번호: int) -> str | None:
    """그 카드 그 번호 효과의 텍스트 한 조각. 모르는 카드·번호면 `None`."""
    정의 = 표.찾기(카드이름)
    if 정의 is None:
        return None
    return 효과조각들(정의.text or "").get(번호)


_발동수꼴 = re.compile(r"^발동\(\s*'(?P<이름>[^']+)'\s*(?:,\s*(?P<번호>\d+))?")
_발동줄꼴 = re.compile(r"^\s{2}(?P<누구>나|상대): (?P<이름>.+?) (?P<번호>\d+)번 (?:강제 )?발동")


def 수_효과문(수: str, 표: 카드표) -> str | None:
    """합법수 문자열이 효과 발동이면 그 효과의 텍스트. 아니면 `None`."""
    맞음 = _발동수꼴.match(수.strip())
    if 맞음 is None:
        return None
    return 효과문(표, 맞음.group("이름"), int(맞음.group("번호") or 1))


def 기보_효과문(줄들: list[str], 표: 카드표) -> list[str]:
    """기보에 「…N번 발동」 줄이 나오면 바로 아래에 그 효과 문면을 한 줄 끼워 넣는다.

    원본 기보(`engine/turn.py` `기보`)는 건드리지 않는다 — CLI·테스트가 쓰는 줄 꼴이
    그대로여야 하고, 이건 화면용 사본이다.
    """
    나온것 = []
    for 줄 in 줄들:
        나온것.append(줄)
        맞음 = _발동줄꼴.match(줄)
        if 맞음 is None:
            continue
        글 = 효과문(표, 맞음.group("이름"), int(맞음.group("번호")))
        if 글:
            나온것.append("    「" + 글 + "」")
    return 나온것


