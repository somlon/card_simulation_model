# 수 갈래 — 합법수 문자열을 "판 위 어디에 묶을 수 있는가" 로 풀어 준다
#
# 사용자 요청(2026-10-28): 선택지 목록을 누르는 대신 마스터 듀얼처럼 패에서 끌어다 놓고
# 카드를 눌러 효과를 고르고 싶다. 화면이 제스처를 수에 묶으려면 문자열을 쪼개 줘야 한다.
# **규칙은 여기 없다** — 합법수를 만드는 것은 `engine/legalmoves.py` 뿐이고, 여기서는
# 이미 만들어진 문자열을 읽기만 한다. 모르는 꼴은 `동작=None` 으로 두어 화면이 목록으로
# 떨어뜨리게 한다(새 동작이 생겨도 조용히 사라지지 않는다).
#
# 두 덱에서 실제로 나오는 동작은 다섯뿐이다(39판 전수 수집, 2026-10-28) —
# 발동 · 소환 · 로드 · 표시변경 · 공격선언.
# ---------------------------------------------------------------------------

_갈래꼴 = re.compile(r"^(?P<동작>[가-힣]+)\((?P<인수>.*)\)$", re.DOTALL)
_따옴표 = re.compile(r"'([^']*)'")


def 수_갈래(수: str, 표: 카드표) -> dict:
    """합법수 하나를 화면이 쓸 사전으로. 꼴을 못 읽으면 `동작`이 `None` 이다."""
    기본 = {"수": 수, "동작": None, "카드": None, "번호": None,
            "표시": None, "대상": None, "효과문": None}
    맞음 = _갈래꼴.match(수.strip())
    if 맞음 is None:
        return 기본
    동작 = 맞음.group("동작")
    인수 = 맞음.group("인수")
    이름들 = _따옴표.findall(인수)
    기본["동작"] = 동작
    기본["카드"] = 이름들[0] if 이름들 else None
    if 동작 == "발동":
        번호맞음 = re.search(r",\s*(\d+)", 인수)
        기본["번호"] = int(번호맞음.group(1)) if 번호맞음 else 1
        기본["효과문"] = 효과문(표, 기본["카드"] or "", 기본["번호"])
    elif 동작 == "표시변경":
        for 말 in ("공격", "수비"):
            if re.search(r"(?<![\w'\"])" + 말 + r"(?![\w'\"])", 인수):
                기본["표시"] = 말
                break
    elif 동작 == "공격선언":
        대상맞음 = re.search(r"대상\s*=\s*'([^']*)'", 인수)
        기본["대상"] = 대상맞음.group(1) if 대상맞음 else None
    # 이름붙은 인수가 더 붙은 수(발동(..., 제거개수=3) 등)는 제스처로 못 줄이므로
    # 화면이 목록 쪽으로 떨어뜨리도록 표시해 둔다.
    기본["곁다리"] = bool(re.search(r"[가-힣]+\s*=", 인수)) and 동작 != "공격선언"
    return 기본


def 수_갈래들(수들: list[str], 표: 카드표) -> list[dict]:
    """합법수 목록을 같은 순서로 갈래 사전 목록으로. 색인이 곧 답할 번호다."""
    return [수_갈래(하나, 표) for 하나 in 수들]
