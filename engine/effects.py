def _표시변경적용(상태, 누구, 자신, 설정, 표, 고르기, 기록, 문맥, 상수: 덱상수 | None = None) -> bool:
    앞뒤값 = 앞뒤.뒷면 if 설정.get("앞뒤면") == "뒷면" else None
    공수값 = 표시.수비 if 설정.get("공수") == "수비" else (표시.공격 if 설정.get("공수") == "공격" else None)
    if 설정.get("전체"):
        # 87회차 「알려진 틈」 1번 — 월식 1 "상대 필드의 모든 몬스터를 뒷면 수비 표시로"
        # (86회차가 `이동`에 연 `전체: true`와 같은 모양). `표시변경`은 존을 안 옮기므로
        # `이동`의 `소유` 분기가 필요 없다.
        후보 = [하나 for 하나 in _고를후보(상태, 누구, 설정["대상"], 자신, 상수, 표) if isinstance(하나, 카드인스턴스)]
        후보 = _비대상효과제외(상태, 후보, 자신, 상수, 표)
        if not 후보:
            return False
        for 하나 in 후보:
            resolve.표시변경(상태, 하나, 앞뒤=앞뒤값, 공수=공수값)
            기록.적기(f"    → {하나.card_id} 표시 바뀜")
        return True
    대상 = _대상하나(상태, 누구, 설정["대상"], 자신, 고르기, 설정.get("이름", "표시변경"), 상수, 표)
    if not isinstance(대상, 카드인스턴스):
        return False
    resolve.표시변경(상태, 대상, 앞뒤=앞뒤값, 공수=공수값)
    기록.적기(f"    → {대상.card_id} 표시 바뀜")
    return True


