def 효과_읽기(폴더: Path | None = None) -> dict[str, dict[int, dict[str, Any]]]:
    """`cards/효과/*.yaml` 을 전부 읽어 `{카드이름: {번호: 항목}}` 으로.

    91회차 — `_발동조건_전부_읽기()`(legalmoves.py)와 같은 이유로 **기본 폴더로 부를 때만**
    프로세스 수명 동안 한 번 캐시한다. 지금까지는 `효과적용기`가 한 게임당 한 번만 읽었지만,
    「알려진 틈」 3번([지속] 상시 효과)이 여는 `지속효과_평가()`는 합법수를 낼 때마다(공격·
    표시변경 후보 하나하나) 이 데이터를 다시 찾아야 해서 캐시 없이는 턴마다 디스크를 다시
    읽는다. 커스텀 `폴더`(시험용)를 넘기면 캐시를 타지 않는다 — 지금까지 그렇게 부르는 전례가
    없었지만(전수 확인), 혹시 생기면 매번 새로 읽어야 맞다."""
    global _효과데이터_캐시
    if 폴더 is None and _효과데이터_캐시 is not None:
        return _효과데이터_캐시
    실제폴더 = 폴더 or 효과폴더
    모음: dict[str, dict[int, dict[str, Any]]] = {}
    if not 실제폴더.exists():
        return 모음
    for 파일 in sorted(실제폴더.glob("*.yaml")):
        실린것 = yaml.safe_load(파일.read_text(encoding="utf-8")) or {}
        if not isinstance(실린것, dict):
            raise 효과오류(f"{파일.name}: 최상위는 카드 이름 사전이라야 한다")
        for 카드이름, 효과들 in 실린것.items():
            if not isinstance(효과들, dict):
                raise 효과오류(f"{파일.name} / {카드이름}: 번호 사전이라야 한다")
            칸 = 모음.setdefault(카드이름, {})
            for 번호, 항목 in 효과들.items():
                if not isinstance(번호, int):
                    raise 효과오류(f"{파일.name} / {카드이름}: 효과 번호는 정수라야 한다")
                if not isinstance(항목, dict):
                    raise 효과오류(f"{파일.name} / {카드이름} {번호}: 사전이라야 한다")
                if "동작" not in 항목 and "미구현" not in 항목 and "미해결" not in 항목:
                    raise 효과오류(
                        f"{파일.name} / {카드이름} {번호}: 동작 · 미구현 · 미해결 중 하나는 있어야 한다"
                    )
                칸[번호] = 항목
    if 폴더 is None:
        _효과데이터_캐시 = 모음
    return 모음


