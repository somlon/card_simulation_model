def _동작들_적용(
    상태, 누구, 자신, 동작목록, 표, 고르기, 기록, 문맥, 상수: 덱상수 | None,
    카드이름: str, 번호: int,
) -> bool:
    """`동작` 목록 하나를 순서대로 돈다. 92회차 — `__call__` 본문이던 이 루프를 재귀
    가능한 함수로 뽑아, `분기`(아래 참조)가 "그러면"·"아니면" 목록을 같은 방식으로
    다시 돌릴 수 있게 한다."""
    무엇이든했나 = False
    사전: dict[str, Any] | None = None
    for 하나 in 동작목록:
        (동작이름, 설정), = 하나.items()
        if 동작이름 == "분기":
            # 92회차, [지속] 다음 조각 (a) — "릴리스 ↔ 카운터 3개 대체 비용"(마르모르·
            # 카르분쿨루스 1번). 여섯 번째 원시 동작이 아니라 기존 다섯 중 어느 쪽을 돌릴지
            # 고르기만 하는 순수 제어 구조다 — 위 모듈 docstring "## 코스트 분기" 참조.
            # `사전`은 분기를 실제로 쓸 때만 짓는다(대부분의 카드는 안 쓴다).
            if 사전 is None:
                사전 = 술어집(상태, 상수 or 덱상수(), 나는=누구).사전()
            분기목록 = 설정["그러면"] if expr.돌리기(설정["조건"], 사전) else 설정.get("아니면", [])
            if _동작들_적용(
                상태, 누구, 자신, 분기목록, 표, 고르기, 기록, 문맥, 상수, 카드이름, 번호
            ):
                무엇이든했나 = True
            continue
        적용 = _원시.get(동작이름)
        if 적용 is None:
            raise 효과오류(f"{카드이름} {번호}번: 모르는 원시 동작 {동작이름!r}")
        if 적용(상태, 누구, 자신, 설정, 표, 고르기, 기록, 문맥, 상수):
            무엇이든했나 = True
    return 무엇이든했나


# ---------------------------------------------------------------- 바깥 창구

class 효과적용기:
    """`engine/turn.py` 의 `수_적용(효과적용=...)` 에 넘기는 호출 가능 객체."""

    def __init__(self, 데이터: dict | None = None, 표: 카드표 | None = None):
        self.데이터 = 데이터 if 데이터 is not None else 효과_읽기()
        self.표 = 표 or 기본카드표()
        self.미구현_기록: list[str] = []

    def __call__(
        self, *, 상태, 카드이름, 번호, 누구, 표, 고르기, 기록, 인수: dict[str, Any] | None = None,
        상수: 덱상수 | None = None,
    ) -> bool:
        항목 = self.데이터.get(카드이름, {}).get(번호)
        if 항목 is None or "동작" not in 항목:
            까닭 = (항목 or {}).get("미구현") or (항목 or {}).get("미해결") or "효과 데이터 없음"
            self.미구현_기록.append(f"{카드이름} {번호}번: {까닭}")
            return False

        자신 = self._자신찾기(상태, 누구, 카드이름)
        기록.적기(f"  {누구}: {카드이름} {번호}번 발동")
        # `인수` 는 합법수의 이름붙은 인수(`발동(..., 제거개수=...)`, 82회차 「알려진 틈」
        # 1번)다. 복사해서 `문맥` 으로 쓴다 — 동작 목록을 돌며 `카운터` 가 `잔량전부` 를
        # 실제 개수로 풀어 되쓰면 뒤따르는 `이동` 이 같은 이름으로 그 수를 읽는다(카드
        # 안에서만 쓰고 버리는 값이라 `self` 에는 안 남긴다). `상수` 도 92회차부터 받는다
        # (`분기` 조건 평가 · `릴리스가능유닛` 대상 말이 덱상수.벽유지최소를 봐야 한다) —
        # 안 넘기는 기존 호출(강제효과_후보들 경로 등)은 `_동작들_적용`이 `덱상수()` 기본값
        # 으로 떨어진다.
        문맥: dict[str, Any] = dict(인수 or {})
        무엇이든했나 = _동작들_적용(
            상태, 누구, 자신, 항목["동작"], 표, 고르기, 기록, 문맥, 상수, 카드이름, 번호
        )
        if not 무엇이든했나:
            기록.적기("    (대상이 없어 불발)")
        return True

    @staticmethod
    def _자신찾기(상태: 게임상태, 누구: str, 카드이름: str) -> 카드인스턴스 | None:
        쪽 = 상태.플레이어(누구)
        모두 = (
            쪽.유닛들(앞면만=False)
            + 쪽.이펙트들(앞면만=False)
            + 쪽.패
            + 쪽.아카이브
            + 쪽.상급덱  # 92회차 — 마르모르·카르분쿨루스 1번처럼 "자신"이 아직 상급덱에
            #                있는 채로 자기 효과로 자기 자신을 특수소환하는 카드가 있다.
            + ([쪽.스킬존] if 쪽.스킬존 else [])
            # 93회차 — 필드 존·공유 존은 테이블 전체에 하나뿐이라(룰지 0-7, `게임상태`에만
            # 있다) 플레이어별 존 목록에 안 들어간다. `게임상태.필드카드들()`이 "소유자가
            # 자신일 때"로 같은 두 존을 넣는 것과 같은 조건 — 지금까지 "자신"을 찾는 전례가
            # 전부 이 두 존 밖 카드였을 뿐인 구멍이었다(턴 종료 훅 머리글 참조).
            + ([상태.필드존] if 상태.필드존 is not None and 상태.필드존.소유 == 누구 else [])
            + ([상태.공유존] if 상태.공유존 is not None and 상태.공유존_소유마커 == 누구 else [])
        )
        for 하나 in 모두:
            if 하나.card_id == 카드이름:
                return 하나
        return None
