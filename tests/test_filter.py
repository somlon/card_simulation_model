    자신 = 카드인스턴스(card_id=이름, 소유="나", 존=존.아카이브)
    자신.턴표지 = {"아카이브로보내짐"}
    상태.나.아카이브 = [자신] + [
        카드인스턴스(card_id=다른이름, 소유="나", 존=존.아카이브)
        for 다른이름 in 다른이름들
    ]


