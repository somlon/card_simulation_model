def _국면(유닛들=(), 패=(), 상급=0, 상대유닛=0, 상대HP=5000):
    나 = 플레이어상태(이름="나")
    상대 = 플레이어상태(이름="상대", hp=상대HP)
    for 자리, (이름, 카운터) in enumerate(유닛들):
        하나 = 카드인스턴스(card_id=이름, 소유="나", 존=존.유닛존, 칸=자리, 표시=표시.수비)
        if 카운터:
            하나.카운터["봉인"] = 카운터
        나.유닛존[자리] = 하나
    나.패 = [카드인스턴스(card_id=이름, 소유="나", 존=존.패) for 이름 in 패]
    나.상급덱 = [
        카드인스턴스(card_id="호박옥 - 아우렘 티라누스", 소유="나", 존=존.상급덱)
        for _ in range(상급)
    ]
    for 자리 in range(상대유닛):
        상대.유닛존[자리] = 카드인스턴스(
            card_id="호박옥 - 결정충", 소유="상대", 존=존.유닛존, 칸=자리
        )
    return 게임상태(나=나, 상대=상대)


