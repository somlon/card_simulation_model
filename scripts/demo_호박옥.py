"""호박옥 맵을 손으로 만든 국면 몇 개에 실제로 돌려 본다.

    python scripts/demo_호박옥.py

국면(카드 배치)은 여전히 손으로 넣는다. `가용수단` 은 2026-10-25부터 `engine.legalmoves.합법수_생성()`
이 채운다 — 일반 소환(37회차) · 표시 형식 변경(38회차) · 공격 선언(39·42회차) · 코스트 없는
「일반」 구분 마법의 발동(43회차, 이 데모가 쓰는 유일한 발동 카드 "호박옥 - 침전"이 여기 해당한다).
발동의 나머지(신속·트리거·지속, 코스트 있는 일반) · 세금차감은 아직 손으로 넣는다(완성 기준 4번은
다섯 동작 전부를 요구하므로 아직 끝나지 않았다 — `engine.legalmoves.커버하지_않음` 참조). 이
스크립트가 보여 주는 것은 **1층 필터가 돌아간다**는 것뿐이다 — 어느 수가 더 좋은지는 1층이
답하지 않는다.
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from engine.legalmoves import 합법수_생성
from engine.mapfilter import 거르기, 맵_검증, 맵_읽기
from engine.predicates import 덱상수, 술어집
from engine.state import 게임상태, 단계, 카드인스턴스, 표시, 플레이어상태, 존

맵경로 = Path(__file__).resolve().parent.parent / "maps" / "호박옥_봉인의_계약.yaml"


def 유닛(이름: str, 카운터: int = 0, 칸: int = 0, **표지) -> 카드인스턴스:
    하나 = 카드인스턴스(card_id=이름, 소유="나", 존=존.유닛존, 칸=칸, 표시=표시.수비)
    if 카운터:
        하나.카운터["봉인"] = 카운터
    for 키, 값 in 표지.items():
        if 값:
            하나.상태표지.add(키)
    return 하나


def 패카드(이름: str) -> 카드인스턴스:
    return 카드인스턴스(card_id=이름, 소유="나", 존=존.패)


def 상급(이름: str) -> 카드인스턴스:
    return 카드인스턴스(card_id=이름, 소유="나", 존=존.상급덱)


def 기본국면() -> 게임상태:
    나 = 플레이어상태(이름="나", hp=5000)
    상대 = 플레이어상태(이름="상대", hp=5000)
    return 게임상태(나=나, 상대=상대, 단계=단계.진행)


def 국면1_세금_위험() -> tuple[str, 게임상태, dict]:
    """잔고 1, 확정 수입 없음 — A 노드의 불변식이 깨지고 '비상 수입 보충'이 열려야 한다."""
    상태 = 기본국면()
    상태.나.유닛존[0] = 유닛("호박옥의 수호자 - 실렉스", 카운터=1)
    상태.나.패 = [패카드("호박옥 - 침전"), 패카드("호박옥의 수호자 - 레시나")]
    상태.나.상급덱 = [상급("호박옥 - 아우렘 티라누스")]
    # 소환 · 발동(침전 — 코스트 없는 「일반」 구분 마법, 43회차) 모두 엔진이 채운다.
    상태.가용수단 = 합법수_생성(상태)
    return "① 잔고 1 · 세금 미납 위험", 상태, {}


def 국면2_수해_전개() -> tuple[str, 게임상태, dict]:
    """패에 태고의 수해가 있고 필드엔 없다 — A 노드 최우선 간선이 열려야 한다."""
    상태 = 기본국면()
    상태.나.유닛존[0] = 유닛("호박옥의 수호자 - 마르모르", 카운터=3)
    상태.나.패 = [패카드("호박옥 - 태고의 수해")]
    상태.나.상급덱 = [상급("호박옥 - 아우렘 티라누스")]
    return "② 태고의 수해 전개 가능", 상태, {}


def 국면3_전멸() -> tuple[str, 게임상태, dict]:
    """필드 몬스터 0장 — 뗄 카운터가 없어 2000 자해. '필드 전멸 경고'가 떠야 한다."""
    상태 = 기본국면()
    상태.나.패 = [패카드("호박옥의 수호자 - 카르분쿨루스")]
    return "③ 필드 전멸 (몬스터 0장)", 상태, {}


def 국면4_피니시() -> tuple[str, 게임상태, dict]:
    """상대 필드가 비었고 티라누스로 리설 — D 노드 다섯 조건을 모두 만족시킨 국면."""
    상태 = 기본국면()
    티 = 유닛("호박옥 - 아우렘 티라누스", 카운터=2, 칸=0)
    티.표시 = 표시.수비
    상태.나.유닛존[0] = 티
    상태.나.유닛존[1] = 유닛("호박옥의 수호자 - 실렉스", 카운터=2, 칸=1)
    상태.상대.hp = 4000
    문맥 = {"제거개수": 2}   # 타격합은 2026-10-25 부터 술어가 계산한다
    return "④ 피니시 — 상대 필드 비었고 리설 사거리", 상태, 문맥


def 국면5_체인방어() -> tuple[str, 게임상태, dict]:
    """상대가 제거 효과를 체인에 올렸고 패에 황금봉랍이 있다 — B 노드 예외가 열려야 한다."""
    상태 = 기본국면()
    상태.나.유닛존[0] = 유닛("호박옥 - 아우렘 티라누스", 카운터=1)
    상태.나.패 = [패카드("호박옥 - 황금봉랍")]
    상태.체인 = [{"발동자": "상대", "card_id": "모르는 카드", "분류": "제거"}]
    return "⑤ 상대 제거 효과 체인 + 황금봉랍", 상태, {}


def 주문():
    대상 = 맵_읽기(맵경로)
    print(f"맵: {대상.덱}  (노드 {len(대상.노드들)}개, 세금 {대상.상수.세금}, "
          f"카운터 「{대상.상수.카운터명}」)")
    print("=" * 78)

    검증 = 맵_검증(대상)
    print("[맵 검증]")
    print("  " + 검증.글로().replace("\n", "\n  "))
    print("=" * 78)

    for 만들기 in (국면1_세금_위험, 국면2_수해_전개, 국면3_전멸, 국면4_피니시, 국면5_체인방어):
        제목, 상태, 문맥 = 만들기()
        print(f"\n{제목}")
        print("-" * 78)
        술 = 상태.나.유닛들()
        print(
            f"  내 유닛 {len(술)}장 / 카운터 합 "
            f"{sum(하나.카운터수('봉인') for 하나 in 술)} / 패 {len(상태.나.패)}장 / "
            f"상대 HP {상태.상대.hp} / 타격합 {술어집(상태, 대상.상수).타격합()}"
        )
        결과 = 거르기(대상, 상태, 문맥)
        print("  " + 결과.글로().replace("\n", "\n  "))
        if 결과.공집합인가:
            print("  (후보 공집합 — 7-1 대로 버그가 아니라 관측 대상으로 기록)")


if __name__ == "__main__":
    주문()
