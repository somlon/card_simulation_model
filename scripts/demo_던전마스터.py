"""던전마스터 셔플! 맵을 손으로 만든 국면 몇 개에 실제로 돌려 본다.

    python scripts/demo_던전마스터.py

호박옥 데모(`scripts/demo_호박옥.py`)와 짝이다 — 완성 기준 4번(합법수 생성)이 두 데모 모두를
요구하므로(`docs/완성_기준.md` 4번) 이 덱에도 같은 자리를 만든다. 국면(카드 배치)은 여전히 손으로
넣지만, `게임상태.가용수단` 자체는 **전부 `engine.legalmoves.합법수_생성()` 이 채운다** — 호박옥
데모처럼 `발동(...)` 을 손으로 더할 필요가 없다. 이 맵(W·X·Z·D·F)의 어떤 간선도 `확정수입()`
말고는 `가용수단`을 읽지 않고, 이 맵은 `확정수입()`을 한 번도 쓰지 않기 때문이다(호박옥만 쓰는
수입 분류 개념 — `data/수입분류.json`이 호박옥 카드만 담고 있다). 그래서 이 데모는 "손으로 넣는
입력 없이 돈다"는 4번의 바를 **가용수단 쪽에서는 이미 넘는다** — 다만 4번 전체가 요구하는 다섯
동작 중 발동·세금차감·공격선언(대상 지정)은 여전히 `engine.legalmoves.커버하지_않음`에 남아
있으므로, 4번 전체 통과는 아니다(1층 필터 자체는 `가용수단`을 거의 안 읽어 그 공백이 이 맵의
후보 출력에는 안 보인다 — 38회차가 이미 적어 둔 경계, 아래 각 국면 출력에도 그대로 나타난다).
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from engine.legalmoves import 합법수_생성
from engine.mapfilter import 거르기, 맵_검증, 맵_읽기
from engine.state import 게임상태, 단계, 앞뒤, 카드인스턴스, 표시, 플레이어상태, 존

맵경로 = Path(__file__).resolve().parent.parent / "maps" / "던전마스터_셔플.yaml"


def 유닛(이름: str, 표시_: 표시 = 표시.수비, 칸: int = 0) -> 카드인스턴스:
    return 카드인스턴스(card_id=이름, 소유="나", 존=존.유닛존, 칸=칸, 표시=표시_)


def 이펙트(이름: str, 소유: str = "나", 칸: int = 0) -> 카드인스턴스:
    return 카드인스턴스(card_id=이름, 소유=소유, 존=존.이펙트존, 칸=칸)


def 패카드(이름: str) -> 카드인스턴스:
    return 카드인스턴스(card_id=이름, 소유="나", 존=존.패)


def 기본국면() -> 게임상태:
    나 = 플레이어상태(이름="나", hp=5000)
    상대 = 플레이어상태(이름="상대", hp=5000)
    return 게임상태(나=나, 상대=상대, 단계=단계.진행)


def 국면1_스킬3번_설치() -> tuple[str, 게임상태, dict]:
    """패에 인페르노 드래곤 — W 노드 '최초 설치 — 스킬 3번' 간선이 열려야 한다.

    패에 레벨 4(계승 불필요) 다크나이트도 둬서 `합법수_생성()` 의 일반 소환 조각이
    같이 채워지는 것도 보인다(W 노드와는 별개 — 이 맵은 소환 자체를 거를 간선이 없다).
    """
    상태 = 기본국면()
    상태.나.패 = [패카드("던전마스터 인페르노 드래곤"), 패카드("던전마스터 다크나이트")]
    return "① 스킬 3번으로 인페르노 드래곤 설치 가능", 상태, {}


def 국면2_다크엠퍼러_설치() -> tuple[str, 게임상태, dict]:
    """패에 데스 칠 드래곤 + 다크 엠퍼러 — W의 두 설치 경로(스킬 3번 · 다크 엠퍼러 1번)가
    동시에 열려야 한다(맵은 고르지 않는다, `.md` 3-4 참고)."""
    상태 = 기본국면()
    상태.나.패 = [패카드("던전마스터 데스 칠 드래곤"), 패카드("던전마스터 다크 엠퍼러")]
    return "② 데스 칠 드래곤 + 다크 엠퍼러 — 설치 경로 둘 다 후보", 상태, {}


def 국면3_재설치_암흑의율법() -> tuple[str, 게임상태, dict]:
    """아카이브에 인페르노, 필드에 암흑의 율법 — W의 '재설치 — 암흑의 율법 2번' 간선.

    필드의 다크나이트(수비 표시)는 `합법수_생성()` 의 표시 형식 변경 조각을 같이 보여 준다
    (W 와는 무관한 별개 수 — 7-1·8장이 '평범한 수에는 맵이 개입하지 않는다'고 해 온 그대로).
    """
    상태 = 기본국면()
    상태.나.아카이브 = [카드인스턴스(card_id="던전마스터 인페르노 드래곤", 소유="나", 존=존.아카이브)]
    상태.나.이펙트존[0] = 이펙트("암흑의 율법")
    상태.나.유닛존[0] = 유닛("던전마스터 다크나이트", 표시.수비)
    return "③ 암흑의 율법 2번 재설치 (+ 표시 변경 후보)", 상태, {}


def 국면4_무료제거_다크나이트() -> tuple[str, 게임상태, dict]:
    """필드에 다크나이트, 상대 필드에 카드 1장 — Z의 '무료 제거' 간선이 열려야 한다."""
    상태 = 기본국면()
    상태.나.유닛존[0] = 유닛("던전마스터 다크나이트", 표시.수비)
    상태.상대.유닛존[0] = 카드인스턴스(
        card_id="던전마스터 깜짝상자", 소유="상대", 존=존.유닛존, 칸=0
    )
    return "④ 다크나이트 1번 — 무료 제거 후보", 상태, {}


def 국면5_교환_선택지() -> tuple[str, 게임상태, dict]:
    """다크엘프 어새신 1번(패에서 특수소환 + 파괴, 무료)은 패에 있어야 조건이 서고 2번
    (필드의 카드를 릴리스 비용으로, 유료)은 필드에 있어야 조건이 선다 — 카드 텍스트상
    서로 다른 존을 요구해(`.md` 5-2·5-3) 둘을 한 국면에서 같이 보려면 패·필드에 각각
    한 장씩 둬야 한다(2장 가정). 5-3 — 유료는 무료를 못 쓸 때의 최후 수단이지만, 그
    우선순위는 상위 층의 일이라 1층은 둘 다 후보로 낸다(맵은 수를 고르지 않는다)."""
    상태 = 기본국면()
    상태.나.패 = [패카드("던전마스터 다크엘프 어새신")]
    상태.나.유닛존[0] = 유닛("던전마스터 다크엘프 어새신", 표시.수비)
    상태.상대.유닛존[0] = 카드인스턴스(
        card_id="던전마스터 깜짝상자", 소유="상대", 존=존.유닛존, 칸=0
    )
    return "⑤ 다크엘프 어새신 (패 1장 + 필드 1장) — 무료·유료 제거 둘 다 후보", 상태, {}


def 국면6_직접공격() -> tuple[str, 게임상태, dict]:
    """전투 단계 · 상대 필드에 앞면 유닛 없음(이펙트 존의 암흑의 율법만 있음, 상대필드카드수()는
    셈) — D 노드(피니시 가설, 간선 없음)와 `합법수_생성()` 의 공격 선언(직접공격) 조각을 같이
    보여 준다. 상대 이펙트 존 카드가 `상대필드카드수()>0`도 채워 Z의 '무료 제거 — 다크 매지션'
    간선까지 열린다(이 카드는 유닛이 아니라 `상대앞면유닛수()`는 0으로 남아 직접공격도 막히지
    않는다)."""
    상태 = 기본국면()
    상태.단계 = 단계.전투
    상태.턴번호 = 2   # 선공의 1턴 금지(룰지 3-3)를 피한다
    상태.나.유닛존[0] = 유닛("던전마스터 다크 매지션", 표시.공격)
    상태.상대.이펙트존[0] = 이펙트("암흑의 율법", 소유="상대")
    return "⑥ 직접공격 가능 (+ 다크 매지션 무료 제거)", 상태, {}


def 주문():
    대상 = 맵_읽기(맵경로)
    print(f"맵: {대상.덱}  (노드 {len(대상.노드들)}개)")
    print("=" * 78)

    검증 = 맵_검증(대상)
    print("[맵 검증]")
    print("  " + 검증.글로().replace("\n", "\n  "))
    print("=" * 78)

    for 만들기 in (
        국면1_스킬3번_설치,
        국면2_다크엠퍼러_설치,
        국면3_재설치_암흑의율법,
        국면4_무료제거_다크나이트,
        국면5_교환_선택지,
        국면6_직접공격,
    ):
        제목, 상태, 문맥 = 만들기()
        print(f"\n{제목}")
        print("-" * 78)
        상태.가용수단 = 합법수_생성(상태)      # 전부 엔진이 채운다 — 손으로 더하지 않는다
        print(f"  합법수_생성() 가용수단: {sorted(상태.가용수단) or '(없음)'}")
        결과 = 거르기(대상, 상태, 문맥)
        print("  " + 결과.글로().replace("\n", "\n  "))
        if 결과.공집합인가:
            print("  (후보 공집합 — 7-1 대로 버그가 아니라 관측 대상으로 기록)")


if __name__ == "__main__":
    주문()
